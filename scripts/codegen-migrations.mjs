#!/usr/bin/env node
// Turn packages/store/migrations/*.sql into a TypeScript module.
//
// The runtime artifact has to carry its own schema. Reading .sql off disk at boot means
// resolving a path from the working directory inside a container, and it means the .sql
// files have to survive the build — two things the previous tree got wrong in three
// separate places, including a path that broke because this repository lives under a
// directory whose name contains a space.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");
const migrationsDir = join(repoRoot, "packages", "store", "migrations");
const outputPath = join(repoRoot, "packages", "store", "src", "migrations.generated.ts");

const check = process.argv.includes("--check");

const entries = (await readdir(migrationsDir))
  .filter((name) => name.endsWith(".sql"))
  .sort();

if (entries.length === 0) {
  console.error("no migrations found in", migrationsDir);
  process.exit(1);
}

const parts = [];
for (const name of entries) {
  const sql = await readFile(join(migrationsDir, name), "utf8");
  const version = name.replace(/\.sql$/, "");
  const digest = createHash("sha256").update(sql, "utf8").digest("hex");
  parts.push({ version, digest, sql });
}

const body = `// GENERATED by scripts/codegen-migrations.mjs — do not edit.
// Source of truth: packages/store/migrations/*.sql

export interface Migration {
  readonly version: string;
  readonly digest: string;
  readonly sql: string;
}

export const MIGRATIONS: readonly Migration[] = [
${parts
  .map(
    (part) =>
      `  {\n    version: ${JSON.stringify(part.version)},\n    digest: ${JSON.stringify(part.digest)},\n    sql: ${JSON.stringify(part.sql)},\n  },`,
  )
  .join("\n")}
];
`;

if (check) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    console.error("migrations.generated.ts is missing; run: node scripts/codegen-migrations.mjs");
    process.exit(1);
  }
  if (current !== body) {
    console.error(
      JSON.stringify({
        ok: false,
        reasonCode: "MIGRATIONS_GENERATED_STALE",
        detail: "packages/store/src/migrations.generated.ts does not match the .sql files",
        fix: "node scripts/codegen-migrations.mjs",
      }),
    );
    process.exit(1);
  }
  console.log(JSON.stringify({ ok: true, migrations: parts.length }));
  process.exit(0);
}

await writeFile(outputPath, body, "utf8");
console.log(
  JSON.stringify({ ok: true, wrote: "packages/store/src/migrations.generated.ts", migrations: parts.length }),
);
